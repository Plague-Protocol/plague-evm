// ── Story — three acts. Acts 1 & 2 fade+collapse when the next act begins. ───
type Act = 1 | 2 | 3
interface StoryLine { text: string; act: Act }

/**
 * The cold open, as a transmission from a containment commander.
 *
 * The speaker is infected and has not turned yet. That is not decoration: it
 * teaches the game's central rule before the player ever sits down — someone
 * can sound completely in command and already be carrying it. The tell is the
 * last fragment of the last line (see TELL_MARK), delivered after the orders,
 * never explained.
 *
 * ⚠ Nine lines in a 3/3/3 act split. Several effects below are keyed to
 * POSITION, not content — the scream fires on `activeLine === 2` as the Act I
 * climax, and act boundaries drive the fade/collapse — so adding, removing or
 * re-grouping lines silently desynchronises the audio from the text. Keep the
 * shape, change the words.
 */
const STORY: StoryLine[] = [
  // Act I — the log
  { text: 'Sector Seven Command. If you hear this, you are inside.', act: 1 },
  { text: 'Day 3 — we sealed the district. Two patients. High fever.', act: 1 },
  { text: 'Day 7 — the hospitals stopped counting.', act: 1 },
  // Act II — the lie
  { text: 'We declared full containment. I signed that order myself.', act: 2 },
  { text: 'We lied.', act: 2 },
  { text: 'It was already past the walls. It came wearing our faces.', act: 2 },
  // Act III — the brief (persists, never fades)
  { text: 'Someone in your room carried it in. They look fine.', act: 3 },
  { text: 'One of you is Patient Zero.', act: 3 },
  { text: 'Trust no one. Find them first. …it is so cold in here.', act: 3 },
]

/** Everything from this marker in the final line is the speaker's tell — it is
 *  rendered as the transmission coming apart rather than as more narration. */
const TELL_MARK = '…'

/**
 * Per-line voiceover.
 *
 * 🔊 ON/OFF IS THE MANIFEST. `VO_DURATIONS_MS` is generated by
 * scripts/generate-vo.py alongside the clips themselves, so an empty array means
 * there is no audio to play and none is requested. There is no separate flag to
 * forget to flip, and no way to ship a flag that disagrees with the files.
 *
 * 🚨 THE CAPTIONS PACE THEMSELVES TO THE VOICE, NOT THE OTHER WAY AROUND.
 * MS_PER_CHAR types at roughly 227 wpm; a composed, grim read lands nearer 130.
 * Every line therefore finished typing well before the voice finished saying it,
 * and the voice ran on over the following caption. Rather than guess a slower
 * fixed rate, each line is typed across its OWN measured clip duration — so text
 * and voice land together whatever read the recording turns out to be.
 *
 * Asset contract, matching the constraints the rest of the splash already obeys:
 *  - Mono, ~56 kbps, band-limited to radio. The whole set is ~170 KB, in line
 *    with the existing tracks in public/sounds (124–679 KB each).
 *  - Radio-degraded and faceless. No name, no portrait — nothing that would have
 *    to be cast, animated, or re-recorded to change.
 *  - The captions are the FLOOR, not a fallback: most mobile sessions are muted
 *    and MiniPay's in-app browser is a muted-by-default context, so the text has
 *    to carry the whole story alone. It already does.
 *
 * Deliberately NOT preloaded — each clip is constructed when its line begins.
 * The splash is where LCP is measured, and pulling the set into the critical
 * path to serve a beat that only starts after a click would regress the
 * PageSpeed numbers tracked in the submission docs.
 */
const VO_AVAILABLE: boolean = VO_DURATIONS_MS.length >= STORY.length
const voSrc = (line: number) => `/sounds/vo/line-${line + 1}.mp3`

/**
 * How long line `i` should take to type.
 *
 * Falls back to the fixed rate whenever there is no voice to match. Clamped so a
 * pathological clip — a botched render, a long silence — cannot leave a caption
 * crawling or flashing past unreadably.
 */
function typingMsFor(i: number, text: string): number {
  const base = text.length * MS_PER_CHAR
  if (!VO_AVAILABLE) return base
  const clip = VO_DURATIONS_MS[i]
  if (!clip || clip <= 0) return base
  return Math.min(base * 3, Math.max(base, clip))
}
const MS_PER_CHAR      = 44
const MS_BETWEEN_LINES = 720
const ACT_FADE_MS      = 1300  // CSS transition duration for fading acts out
const ACT_PAUSE_MS     = 2000  // total pause (fade + settle) before next act types

// ── Per-line render state ─────────────────────────────────────────────────────
interface LineState {
  text:      string
  full:      string
  opacity:   number
  collapsed: boolean
  act:       1 | 2 | 3
}

// ── Pure state-updater factories ──────────────────────────────────────────────
function fadeAct(act: Act) {
  return (prev: LineState[]) => prev.map(l => l.act === act ? { ...l, opacity: 0 } : l)
}
function collapseAct(act: Act) {
  return (prev: LineState[]) => prev.map(l => l.act === act ? { ...l, collapsed: true } : l)
}
function startLine(i: number, text: string, act: Act) {
  return (prev: LineState[]) => {
    const next = [...prev]
    next[i] = { text: '', full: text, opacity: 1, collapsed: false, act }
    return next
  }
}
function updateChar(i: number, text: string, c: number) {
  return (prev: LineState[]) =>
    prev.map((l, idx) => idx === i ? { ...l, text: text.slice(0, c) } : l)
}
function completeLine(i: number, text: string) {
  return (prev: LineState[]) =>
    prev.map((l, idx) => idx === i ? { ...l, text } : l)
}

// ── Async typewriter — only runs once active is true ──────────────────────────
function useStoryTypewriter(active: boolean) {
  const [lines, setLines]           = useState<LineState[]>([])
  const [activeLine, setActiveLine] = useState(0)
  const [done, setDone]             = useState(false)

  useEffect(() => {
    if (!active) return
    setLines([])
    setActiveLine(0)
    setDone(false)

    let cancelled = false
    const wait = (ms: number) => new Promise<void>(r => setTimeout(r, ms))

    async function transitionAct(fadingAct: Act) {
      setLines(fadeAct(fadingAct))
      setTimeout(() => { if (!cancelled) setLines(collapseAct(fadingAct)) }, ACT_FADE_MS + 100)
      await wait(ACT_PAUSE_MS)
    }

    async function typeLine(i: number, text: string, act: Act) {
      setActiveLine(i)
      setLines(startLine(i, text, act))
      // Per-character delay is derived from this line's own budget, so a line
      // with a voiceover types across exactly as long as the voice takes to say
      // it and the two finish together. Without audio this resolves to the flat
      // MS_PER_CHAR the splash has always used.
      const perChar = typingMsFor(i, text) / Math.max(1, text.length)
      await wait(perChar)
      for (let c = 1; c <= text.length; c++) {
        if (cancelled) return
        setLines(updateChar(i, text, c))
        if (c < text.length) await wait(perChar)
      }
      if (!cancelled) setLines(completeLine(i, text))
      await wait(MS_BETWEEN_LINES)
    }

    async function run() {
      let prevAct: number | null = null
      for (let i = 0; i < STORY.length; i++) {
        if (cancelled) return
        const { text, act } = STORY[i]
        if (prevAct !== null && act !== prevAct) {
          await transitionAct(prevAct as Act)
          if (cancelled) return
        }
        await typeLine(i, text, act)
        prevAct = act
      }
      if (!cancelled) setDone(true)
    }

    run()
    return () => { cancelled = true }
  }, [active])

  return { lines, activeLine, done }
}

// ── Connection-aware gating ───────────────────────────────────────────────────
/**
 * True when the ~1 MB gate clip should never be fetched.
 *
 * `saveData` is the user explicitly asking for less traffic. `effectiveType`
 * is Chrome's own estimate from observed RTT/throughput, so it catches a
 * genuinely slow link even when the radio claims 4G — which is the common case
 * on the mid-range Android hardware MiniPay runs on. Absent the API (Safari,
 * Firefox) we assume a good connection and behave as before.
 */
function shouldSkipGateClip(): boolean {
  if (typeof navigator === 'undefined') return false
  const c = (navigator as Navigator & {
    connection?: { saveData?: boolean; effectiveType?: string }
  }).connection
  if (!c) return false
  if (c.saveData) return true
  return ['slow-2g', '2g', '3g'].includes(c.effectiveType ?? '')
}

