// ── Component ─────────────────────────────────────────────────────────────────
export function SplashScreen({ onResolved }: { onResolved?: () => void } = {}) {
  const [visible,      setVisible]      = useState(false)
  const [exiting,      setExiting]      = useState(false)
  const [finaleStatic, setFinaleStatic] = useState(false)
  const [titleSlam,    setTitleSlam]    = useState(false)
  const [splashMuted,  setSplashMuted]  = useState(false)
  const [bgIndex,      setBgIndex]      = useState(0)
  // The gate clip is ~1 MB of decorative loop. `autoPlay` makes the browser
  // fetch it during initial load no matter what `preload` says, so it competed
  // with everything that actually matters on a phone. Mount it only once the
  // page has settled; GATE_POSTER holds the frame until then, so there is no
  // visible gap. See the payload notes in docs/CELO_STARTUPBANK_SUBMISSION.md.
  const [videoReady,   setVideoReady]   = useState(false)
  // gate = logo screen requiring a click; story = typewriter + audio running
  const [phase,        setPhase]        = useState<'gate' | 'story'>('gate')

  const ambientRef         = useRef<HTMLAudioElement | null>(null)
  const transientAudiosRef = useRef<HTMLAudioElement[]>([])
  const lastHeartbeatRef   = useRef(0)

  // Track and play a one-shot Audio so the mute toggle can stop it later.
  const playOneShot = useCallback((src: string, volume: number) => {
    const audio = new Audio(src)
    audio.volume = volume
    transientAudiosRef.current.push(audio)
    audio.addEventListener('ended', () => {
      transientAudiosRef.current = transientAudiosRef.current.filter(a => a !== audio)
    })
    audio.play().catch(() => {})
    return audio
  }, [])

  // Voiceover elements pre-created inside the gate gesture (see beginStory).
  const voPoolRef = useRef<HTMLAudioElement[]>([])

  const stopAllTransients = useCallback(() => {
    const audios = transientAudiosRef.current
    transientAudiosRef.current = []
    for (const audio of audios) audio.pause()
    for (const clip of voPoolRef.current) clip.pause()
  }, [])

  /**
   * Play voiceover line `i` from the pool unlocked at the gate.
   *
   * Falls back to a fresh element if the pool is empty — desktop browsers do
   * not need the unlock, and a muted reader who unmutes mid-story never built
   * one. On mobile that fallback is the silent path the pool exists to avoid,
   * which is why it is a fallback and not the default.
   */
  const playVoLine = useCallback((i: number, volume: number) => {
    // Exactly one line speaks at a time. The pool's clips live outside
    // transientAudiosRef, so stopAllTransients does not clamp them the way it
    // clamped the old per-line elements — silence the rest here instead.
    for (const [j, clip] of voPoolRef.current.entries()) {
      if (j === i) continue
      clip.pause()
      clip.currentTime = 0
    }
    const pooled = voPoolRef.current[i]
    if (pooled) {
      pooled.currentTime = 0
      pooled.volume = volume
      pooled.play().catch(() => {})
      return pooled
    }
    return playOneShot(voSrc(i), volume)
  }, [playOneShot])

  const { lines, activeLine, done } = useStoryTypewriter(phase === 'story')

  // Act III triggers the finale zombie clip — fades in behind the climax text
  const inAct3 = phase === 'story' && (lines[activeLine]?.act === 3 || done)

  // ── First-time visitor ───────────────────────────────────────────────────────
  useEffect(() => {
    const seen = globalThis.window !== undefined && sessionStorage.getItem('plague_intro_seen')
    if (!seen) {
      setVisible(true)
    } else {
      onResolved?.()
    }
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [])

  // ── Lock body scroll while splash is open ────────────────────────────────────
  useEffect(() => {
    document.body.style.overflow = visible ? 'hidden' : ''
    return () => { document.body.style.overflow = '' }
  }, [visible])

  // ── Defer the gate clip until everything critical has loaded ─────────────────
  // Keyed off the window `load` event rather than requestIdleCallback: idle can
  // fire while the network is still saturated, which put ~1 MB of video in front
  // of the image the page's LCP depends on. `load` is self-tuning — it fires
  // almost immediately on a fast connection and genuinely waits on a slow one.
  useEffect(() => {
    if (!visible) return
    // Skip the clip outright when the connection says not to. It is ~1 MB of
    // pure decoration and the poster frame underneath is visually almost
    // identical, so on a metered or slow link it is the single easiest MB to
    // not spend — and this is exactly the MiniPay audience: mid-range Android
    // on mobile data. Data Saver is an explicit user request; honour it.
    if (shouldSkipGateClip()) return
    let timer: ReturnType<typeof setTimeout>
    const arm = () => { timer = setTimeout(() => setVideoReady(true), 600) }
    if (document.readyState === 'complete') { arm(); return () => clearTimeout(timer) }
    globalThis.addEventListener('load', arm, { once: true })
    return () => { globalThis.removeEventListener('load', arm); clearTimeout(timer) }
  }, [visible])

  // ── Background crossfade — independent 4.5 s timer ───────────────────────────
  useEffect(() => {
    if (!visible) return
    setBgIndex(0)
    const id = setInterval(() =>
      setBgIndex(i => Math.min(BG_FRAMES.length - 1, i + 1)), 4500)
    return () => clearInterval(id)
  }, [visible])

  // ── Gate click — starts audio synchronously inside the user gesture ──────────
  const beginStory = useCallback(() => {
    if (phase !== 'gate') return
    if (!splashMuted) {
      const audio = new Audio(AMBIENT_TRACK)
      audio.loop   = true
      audio.volume = 0.28
      ambientRef.current = audio
      audio.play().catch(() => {})

      // Unlock every voiceover clip HERE, inside the gesture.
      //
      // Mobile Safari grants playback per element, and only to elements
      // created while a user gesture is live. `new Audio(src)` at the moment a
      // line starts typing is seconds too late and is rejected silently by the
      // `.catch(() => {})` in playOneShot — so on a first visit only line 1
      // spoke. Each visit then cached one more clip, letting it start fast
      // enough to squeak through, which is why the story gained a line per
      // reload rather than failing outright.
      //
      // So: build all nine now, start each one muted, and pause it. That
      // play() call is what actually confers permission; from then on the
      // element is unlocked for the rest of the session and the story can
      // play it whenever the line arrives.
      // Each clip is played muted and paused again immediately. Pausing
      // SYNCHRONOUSLY — rather than in the play() promise's .then() — matters:
      // those nine promises resolve at unpredictable moments, and a late one
      // landing after the story had begun would pause a line mid-sentence or
      // unmute a clip that was still running its unlock playback, so several
      // voices talked over each other. pause() is synchronous and the
      // permission is already granted by the play() call itself, so there is
      // nothing to wait for.
      voPoolRef.current = VO_DURATIONS_MS.map((_, i) => {
        const clip = new Audio(voSrc(i))
        clip.preload = 'auto'
        clip.muted = true
        clip.play().catch(() => {})
        clip.pause()
        clip.currentTime = 0
        clip.muted = false
        return clip
      })
    }
    setPhase('story')
  }, [phase, splashMuted])

  // ── Cleanup ambient + transients on visible reset ───────────────────────────
  useEffect(() => {
    if (visible) return
    ambientRef.current?.pause()
    if (ambientRef.current) ambientRef.current.currentTime = 0
    ambientRef.current = null
    stopAllTransients()
    // Drop the unlocked pool too: the next gate click builds a fresh one
    // inside its own gesture, which is the only way it gets permission again.
    voPoolRef.current = []
  }, [visible, stopAllTransients])

  // ── Respond to mute toggle on existing ambient + one-shot audio ──────────────
  useEffect(() => {
    if (splashMuted) {
      ambientRef.current?.pause()
      stopAllTransients()
      return
    }
    const audio = ambientRef.current
    if (!audio) return
    audio.volume = 0.28
    audio.play().catch(() => {})
  }, [splashMuted, stopAllTransients])

  // ── Heartbeat — rate-limited to max once per 1.4 s ───────────────────────────
  useEffect(() => {
    if (!visible || splashMuted || phase !== 'story') return
    const now = Date.now()
    if (now - lastHeartbeatRef.current < 1400) return
    lastHeartbeatRef.current = now
    playOneShot('/sounds/heartbeat.mp3', 0.18)
  }, [activeLine, visible, splashMuted, phase, playOneShot])

  // ── Voiceover — one clip per line, cued as that line starts typing ──────────
  // Per-line rather than one track over the whole intro: the typewriter is
  // self-paced and skippable, so a single welded track would drift out of sync
  // the first time a line ran long and would keep talking over a skip.
  useEffect(() => {
    if (!VO_AVAILABLE || !visible || splashMuted || phase !== 'story') return
    const vo = playVoLine(activeLine, 0.55)
    // Stop this line's voice if the reader skips or mutes mid-sentence;
    // stopAllTransients covers the global cases, this covers line changes.
    return () => { vo.pause() }
  }, [activeLine, visible, splashMuted, phase, playVoLine])

  // ── Scream — fires at Act I climax (line 2 "Day 7…"), echoes out over 4 s ────
  useEffect(() => {
    if (!visible || activeLine !== 2 || splashMuted || phase !== 'story') return
    let fade: ReturnType<typeof setInterval> | null = null
    const fire = setTimeout(() => {
      const scream = playOneShot(SCREAM_TRACK, 0.24)
      let step = 0
      fade = setInterval(() => {
        step++
        scream.volume = Math.max(0, 0.24 * (1 - step / 20))
        if (step >= 20) { if (fade) clearInterval(fade); scream.pause() }
      }, 200)
    }, 500)
    return () => {
      clearTimeout(fire)
      if (fade) clearInterval(fade)
    }
  }, [activeLine, visible, splashMuted, phase, playOneShot])

  // ── Skip entire intro immediately ───────────────────────────────────────────
  const skipAll = useCallback(() => {
    if (globalThis.window !== undefined) sessionStorage.setItem('plague_intro_seen', '1')
    ambientRef.current?.pause()
    if (ambientRef.current) ambientRef.current.currentTime = 0
    ambientRef.current = null
    stopAllTransients()
    setVisible(false)
    onResolved?.()
  }, [stopAllTransients, onResolved])

  // ── Dismiss / finale ─────────────────────────────────────────────────────────
  const dismiss = useCallback(() => {
    if (exiting || finaleStatic) return
    if (globalThis.window !== undefined) sessionStorage.setItem('plague_intro_seen', '1')
    setFinaleStatic(true)
    setTitleSlam(true)
    if (!splashMuted) {
      playOneShot('/sounds/reveal-sting.mp3', 0.35)
    }
    setTimeout(() => setExiting(true), 260)
    if (ambientRef.current) { ambientRef.current.pause(); ambientRef.current.currentTime = 0 }
    setTimeout(() => {
      stopAllTransients()
      setVisible(false); setFinaleStatic(false); setTitleSlam(false); onResolved?.()
    }, 900)
  }, [exiting, finaleStatic, splashMuted, playOneShot, stopAllTransients, onResolved])

  // ── Keyboard dismiss (only during story) ─────────────────────────────────────
  useEffect(() => {
    if (!visible || phase !== 'story') return
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Enter' || e.key === ' ' || e.key === 'Escape') dismiss()
    }
    globalThis.addEventListener('keydown', onKey)
    return () => globalThis.removeEventListener('keydown', onKey)
  }, [visible, dismiss, phase])

  if (!visible) return null

  return (
    <dialog
      open
      aria-label="Zombie Plague intro"
      style={{
        position:        'fixed',
        inset:           0,
        width:           '100vw',
        height:          '100vh',
        maxWidth:        '100vw',
        maxHeight:       '100vh',
        zIndex:          9999,
        display:         'flex',
        flexDirection:   'column',
        alignItems:      'center',
        justifyContent:  'center',
        backgroundColor: '#000',
        overflow:        'hidden',
        border:          'none',
        padding:         0,
        margin:          0,
        animation: exiting
          ? 'splash-exit 0.8s ease-in forwards'
          : 'splash-enter 0.6s ease-out both',
      }}
    >
      {/* Mute toggle — only shown once story is running */}
      {phase === 'story' && (
        <button
          onClick={() => setSplashMuted(m => !m)}
          aria-label={splashMuted ? 'Unmute intro audio' : 'Mute intro audio'}
          style={{
            position:        'absolute',
            top:             '1rem',
            right:           '1rem',
            zIndex:          10,
            display:         'flex',
            alignItems:      'center',
            gap:             '0.4rem',
            background:      'rgba(6,11,6,0.7)',
            border:          '1px solid rgba(107,142,35,0.35)',
            borderRadius:    '6px',
            padding:         '0.4rem 0.75rem',
            cursor:          'pointer',
            fontFamily:      'var(--font-mono)',
            fontSize:        '0.65rem',
            letterSpacing:   '0.14em',
            color:           splashMuted ? '#7d9a72' : '#6b8e23',
            backdropFilter:  'blur(8px)',
          }}
        >
          <span style={{ fontSize: '1rem', lineHeight: 1 }}>{splashMuted ? '🔇' : '🔊'}</span>
          <span>{splashMuted ? 'MUTED' : 'SOUND ON'}</span>
        </button>
      )}

      {/* Skip button — always visible in both phases */}
      <button
        onClick={skipAll}
        aria-label="Skip intro"
        style={{
          position:      'absolute',
          top:           '1rem',
          left:          '1rem',
          zIndex:        10,
          display:       'flex',
          alignItems:    'center',
          gap:           '0.35rem',
          background:    'rgba(6,11,6,0.7)',
          border:        '1px solid rgba(212,201,178,0.25)',
          borderRadius:  '6px',
          padding:       '0.4rem 0.75rem',
          cursor:        'pointer',
          fontFamily:    'var(--font-mono)',
          fontSize:      '0.65rem',
          letterSpacing: '0.14em',
          color:         'rgba(212,201,178,0.7)',
          backdropFilter: 'blur(8px)',
          transition:    'color 0.15s, border-color 0.15s',
        }}
        onMouseEnter={e => {
          (e.currentTarget as HTMLButtonElement).style.color = '#d4c9b2';
          (e.currentTarget as HTMLButtonElement).style.borderColor = 'rgba(212,201,178,0.5)';
        }}
        onMouseLeave={e => {
          (e.currentTarget as HTMLButtonElement).style.color = 'rgba(212,201,178,0.7)';
          (e.currentTarget as HTMLButtonElement).style.borderColor = 'rgba(212,201,178,0.25)';
        }}
      >
        <span>SKIP</span>
        <span style={{ fontSize: '0.75rem', lineHeight: 1 }}>››</span>
      </button>

      {/* Background layers — stacked, crossfade via opacity transition.
          Only the current frame and the next one are mounted: rendering all
          four up front made the browser fetch every background image during
          initial load, for art the viewer would not see for another 4.5-13.5s.
          The +1 lookahead keeps the next frame decoded before its crossfade.

          Gated on the story phase. These sit BEHIND the gate's poster/video, so
          during the gate they are invisible — yet mounting them there still cost
          ~385 KB (bg-horror 148 KB + bg-zombie-portrait 237 KB) of contention on
          the initial load. On Slow 4G that starved the hero image the page's LCP
          depends on: a preloaded 31 KB file was not finishing until 7.7s, and
          mobile Performance on `/` dropped to 71. */}
      {phase === 'story' && (
      <div style={{ position: 'absolute', inset: 0, zIndex: 0 }}>
        {BG_FRAMES.filter((_, i) => i <= bgIndex + 1).map((src, i) => (
          <div key={src} style={{
            position:           'absolute',
            inset:              0,
            backgroundImage:    `url(${src})`,
            backgroundSize:     'cover',
            backgroundPosition: 'center',
            transform:          'scale(1.04)',
            filter:             'saturate(0.9) contrast(1.05) brightness(0.38)',
            opacity:            i === bgIndex ? 1 : 0,
            transition:         'opacity 2.5s ease',
          }} />
        ))}
      </div>
      )}

      {/* Poster frame — holds the gate's look while the clip is deferred. */}
      {phase === 'gate' && !videoReady && (
        <div
          aria-hidden="true"
          style={{
            position:           'absolute',
            inset:              0,
            zIndex:             0,
            backgroundImage:    `url(${GATE_POSTER})`,
            backgroundSize:     'cover',
            backgroundPosition: 'center',
            filter:             'saturate(0.7) contrast(1.1) brightness(0.5)',
            opacity:            0.85,
          }}
        />
      )}

      {/* Zombie video — pre-splash gate */}
      {phase === 'gate' && videoReady && (
        <video
          src={GATE_VIDEO}
          poster={GATE_POSTER}
          autoPlay
          muted
          loop
          playsInline
          preload="metadata"
          aria-hidden="true"
          style={{
            position:      'absolute',
            inset:         0,
            zIndex:        0,
            width:         '100%',
            height:        '100%',
            objectFit:     'cover',
            filter:        'saturate(0.7) contrast(1.1) brightness(0.5)',
            opacity:       0.85,
            pointerEvents: 'none',
          }}
        />
      )}

      {/* Zombie video — Act III climax (fades in over the image stack) */}
      {phase === 'story' && (
        <video
          src={FINALE_VIDEO}
          autoPlay
          muted
          loop
          playsInline
          aria-hidden="true"
          style={{
            position:    'absolute',
            inset:       0,
            zIndex:      0,
            width:       '100%',
            height:      '100%',
            objectFit:   'cover',
            filter:      'saturate(0.7) contrast(1.15) brightness(0.42)',
            opacity:     inAct3 ? 0.7 : 0,
            transition:  'opacity 1.6s ease',
            pointerEvents: 'none',
          }}
        />
      )}

      {/* Scanlines */}
      <div style={{
        position:        'absolute',
        inset:           0,
        zIndex:          1,
        backgroundImage: 'repeating-linear-gradient(0deg, transparent, transparent 2px, rgba(0,0,0,0.18) 2px, rgba(0,0,0,0.18) 4px)',
        pointerEvents:   'none',
      }} />

      {/* Finale static burst */}
      <div style={{
        position:        'absolute',
        inset:           0,
        zIndex:          3,
        pointerEvents:   'none',
        opacity:         finaleStatic ? 0.55 : 0,
        transition:      'opacity 0.18s ease',
        backgroundImage: 'radial-gradient(circle at 20% 10%, rgba(255,255,255,0.38) 0 1px, transparent 1px), radial-gradient(circle at 80% 70%, rgba(255,255,255,0.28) 0 1px, transparent 1px), radial-gradient(circle at 55% 30%, rgba(255,255,255,0.42) 0 1px, transparent 1px)',
        backgroundSize:  '6px 6px, 8px 8px, 5px 5px',
        animation:       finaleStatic ? 'splash-static 0.22s steps(4) infinite' : 'none',
      }} />

      {/* Floating particles */}
      <div style={{ position: 'absolute', inset: 0, pointerEvents: 'none', zIndex: 0 }}>
        {PARTICLES.map(p => (
          <span key={p.id} style={{
            position:        'absolute',
            bottom:          '-12px',
            left:            `${p.x}%`,
            width:           `${p.size}px`,
            height:          `${p.size}px`,
            borderRadius:    '50%',
            backgroundColor: 'rgba(107,142,35,0.35)',
            boxShadow:       '0 0 6px rgba(107,142,35,0.5)',
            animation:       `splash-particle ${p.duration}s ${p.delay}s ease-in infinite`,
          }} />
        ))}
      </div>

      {/* Blood vignette */}
      <div style={{
        position:      'absolute',
        inset:         0,
        zIndex:        1,
        pointerEvents: 'none',
        background:    'linear-gradient(180deg, rgba(0,0,0,0.25) 0%, rgba(0,0,0,0.7) 100%), radial-gradient(ellipse at center, transparent 35%, rgba(180,0,0,0.22) 100%)',
      }} />

      {/* ── Gate phase — click to unlock audio + begin story ─────────────────── */}
      {phase === 'gate' && (
        <div style={{
          position:      'relative',
          zIndex:        2,
          display:       'flex',
          flexDirection: 'column',
          alignItems:    'center',
          gap:           '1.5rem',
          padding:       '1rem',
          textAlign:     'center',
        }}>
          {/* LCP anchor. Every other visual on this screen is `inset: 0`, and
              Chrome excludes full-viewport images from Largest Contentful Paint
              as backgrounds — so before this existed the gate offered no LCP
              candidate at all and Lighthouse returned NO_LCP, which voids the
              entire Performance score. This img is deliberately bounded (not
              full-bleed) and its animation touches transform only: an ancestor
              or self opacity of 0 would make it ineligible again. */}
          <img
            src="/images/splash-mark.webp"
            alt=""
            width={224}
            height={224}
            fetchPriority="high"
            decoding="sync"
            style={{
              width:     'clamp(7rem, 30vw, 14rem)',
              height:    'auto',
              animation: 'splash-mark-pulse 3s ease-in-out infinite',
              filter:    'drop-shadow(0 0 24px rgba(230,51,41,0.8))',
            }}
          />

          <h1 style={{
            fontFamily:    'var(--font-display)',
            fontSize:      'clamp(2.4rem, 7vw, 4.2rem)',
            lineHeight:    1,
            color:         '#d4c9b2',
            letterSpacing: '0.06em',
            textShadow:    '0 0 30px rgba(230,51,41,0.5)',
            margin:        0,
          }}>
            ZOMBIE PLAGUE
          </h1>

          {/* 🚨 THE LABEL HAS TO DESCRIBE WHAT THE BUTTON DOES.
              "DARE TO ENTER" promised the game and delivered a cutscene, so the
              first thing it did was break its own promise — and it framed the
              splash as a dare, which is a different tone from the one the
              transmission actually has. The speaker names themselves in the
              first line ("Sector Seven Command"), so the button borrows their
              words. It also sets up the reveal: this is a message from the
              officer who signed the containment order, and by the last line you
              learn what happened to them.

              Sized with clamps and nowrap because it is 20 characters against
              13 — at a fixed 1rem and 0.28em of tracking it overflowed a 375px
              phone. */}
          <button
            onClick={beginStory}
            style={{
              marginTop:       '0.5rem',
              padding:         'clamp(0.7rem, 2.4vw, 0.75rem) clamp(1.1rem, 6vw, 2.5rem)',
              fontFamily:      'var(--font-mono)',
              fontSize:        'clamp(0.72rem, 3vw, 1rem)',
              letterSpacing:   '0.2em',
              whiteSpace:      'nowrap',
              textTransform:   'uppercase',
              fontWeight:      700,
              color:           '#060b06',
              backgroundColor: '#6b8e23',
              border:          '2px solid #6b8e23',
              borderRadius:    '6px',
              cursor:          'pointer',
              boxShadow:       '0 0 24px rgba(107,142,35,0.6)',
              animation:       'splash-pulse 2s ease-in-out infinite',
            }}
            onMouseEnter={e => {
              (e.currentTarget as HTMLButtonElement).style.boxShadow = '0 0 40px rgba(107,142,35,0.9)'
            }}
            onMouseLeave={e => {
              (e.currentTarget as HTMLButtonElement).style.boxShadow = '0 0 24px rgba(107,142,35,0.6)'
            }}
          >
            Message from Command
          </button>

          <p style={{
            fontFamily:    'var(--font-mono)',
            fontSize:      '0.62rem',
            letterSpacing: '0.14em',
            color:         '#7d9a72',
            margin:        0,
          }}>
            {/* CLICK TO BEGIN · AUDIO ENABLED */}
          </p>
        </div>
      )}

      {/* ── Story phase — typewriter + enter button ───────────────────────────── */}
      {phase === 'story' && (
        <div style={{
          position:      'relative',
          zIndex:        2,
          display:       'flex',
          flexDirection: 'column',
          alignItems:    'center',
          gap:           '1.25rem',
          padding:       '1rem',
          maxWidth:      '600px',
          width:         '100%',
          textAlign:     'center',
        }}>

          {/* Biohazard + title */}
          <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', gap: '0.6rem' }}>
            <div style={{
              fontSize:  'clamp(2.5rem, 10vw, 4rem)',
              lineHeight: 1,
              animation: 'splash-pulse 3s ease-in-out infinite',
              filter:    'drop-shadow(0 0 24px rgba(230,51,41,0.8))',
            }}>☣</div>

            <h1 style={{
              fontFamily:    'var(--font-display)',
              fontSize:      'clamp(2.4rem, 7vw, 4.2rem)',
              lineHeight:    1,
              color:         '#d4c9b2',
              letterSpacing: '0.06em',
              textShadow:    '0 0 30px rgba(230,51,41,0.5)',
              margin:        0,
              transform:     titleSlam ? 'scale(1.12) skewX(-2deg)' : 'scale(1)',
              transition:    'transform 0.2s cubic-bezier(0.2, 0.8, 0.2, 1)',
            }}>
              ZOMBIE PLAGUE
            </h1>
          </div>

          {/* Story lines — fade+collapse between acts */}
          <div style={{ width: '100%', display: 'flex', flexDirection: 'column', alignItems: 'center' }}>
            {lines.map((line, i) => {
              const isAct3   = line.act === 3
              const isClimaxLine = i === STORY.length - 1
              const isClimax = isAct3 && isClimaxLine && done
              // 16px reading floor (project type-scale policy) — story text is
              // body copy, not decoration.
              let fontSize = '1rem'
              if (isAct3) fontSize = i === STORY.length - 1 ? '1.3rem' : '1.1rem'
              let marginBottom: string | number = isAct3 ? '0.55rem' : '0.32rem'
              if (line.collapsed) marginBottom = 0
              let textColor = '#7a8c74'
              if (isAct3) textColor = '#d4c9b2'
              if (isClimax) textColor = '#e63329'
              const cursor = i === activeLine && !done
                ? { borderRight: '2px solid #6b8e23', paddingRight: '4px' }
                : {}
              return (
                <div key={line.full} style={{
                  opacity:      line.opacity,
                  // 4.5rem fits ~2.5 wrapped lines at the 1.1–1.3rem Act III
                  // sizes, so a line that wraps to three — "One of you is
                  // Patient Zero." on a narrow viewport — lost its last word to
                  // `overflow: hidden`. The cap exists only to animate the
                  // collapse between acts, so it now applies only while
                  // collapsing; an open line is bounded by its own content.
                  maxHeight:    line.collapsed ? '0px' : '20rem',
                  overflow:     'hidden',
                  transition:   `opacity ${ACT_FADE_MS}ms ease, max-height ${ACT_FADE_MS + 200}ms ease, margin-bottom ${ACT_FADE_MS + 200}ms ease`,
                  marginBottom,
                  width:        '100%',
                  textAlign:    'center',
                }}>
                  <p style={{
                    margin:        0,
                    fontFamily:    'var(--font-mono)',
                    fontSize,
                    lineHeight:    1.45,
                    letterSpacing: isAct3 ? '0.04em' : '0.06em',
                    paddingRight:  '0.12em',
                    color:      textColor,
                    textShadow: isClimax ? '0 0 14px rgba(230,51,41,0.75)' : 'none',
                    fontWeight: isAct3 ? 600 : 400,
                    ...cursor,
                  }}>
                    {/* The tell. On the final line only, the fragment after the
                        ellipsis is rendered as the transmission degrading —
                        dimmer, unsteady, no longer in the commander's voice.
                        Deliberately a VISUAL effect: it has to land for the
                        muted majority, who will never hear the performance. */}
                    {isClimaxLine && line.text.includes(TELL_MARK) ? (
                      <>
                        {line.text.slice(0, line.text.indexOf(TELL_MARK))}
                        <span style={{
                          color:      '#8a6f68',
                          fontStyle:  'italic',
                          fontWeight: 400,
                          textShadow: '0 0 10px rgba(230,51,41,0.35)',
                          animation:  'splash-tell 2.4s ease-in-out infinite',
                        }}>
                          {line.text.slice(line.text.indexOf(TELL_MARK))}
                        </span>
                      </>
                    ) : line.text}
                  </p>
                </div>
              )
            })}
          </div>

          {/* ENTER button — appears when story finishes */}
          <button
            onClick={dismiss}
            disabled={exiting || finaleStatic}
            style={{
              marginTop:     '0.25rem',
              padding:       '0.75rem 2.5rem',
              fontFamily:    'var(--font-mono)',
              fontSize:      '1rem',
              letterSpacing: '0.28em',
              textTransform: 'uppercase',
              fontWeight:    700,
              color:         '#060b06',
              backgroundColor: '#6b8e23',
              border:        '2px solid #6b8e23',
              borderRadius:  '6px',
              cursor:        'pointer',
              boxShadow:     '0 0 24px rgba(107,142,35,0.6)',
              opacity:       done ? 1 : 0,
              transform:     done ? 'translateY(0)' : 'translateY(8px)',
              transition:    'opacity 0.6s ease, transform 0.6s ease, box-shadow 0.2s',
              pointerEvents: done && !exiting && !finaleStatic ? 'auto' : 'none',
            }}
            onMouseEnter={e => {
              (e.currentTarget as HTMLButtonElement).style.boxShadow = '0 0 40px rgba(107,142,35,0.9)'
            }}
            onMouseLeave={e => {
              (e.currentTarget as HTMLButtonElement).style.boxShadow = '0 0 24px rgba(107,142,35,0.6)'
            }}
          >
            ENTER
          </button>

          <p style={{
            fontFamily:    'var(--font-mono)',
            fontSize:      '0.65rem',
            letterSpacing: '0.15em',
            color:         '#7d9a72',
            margin:        0,
            opacity:       done ? 0.7 : 0,
            transition:    'opacity 0.8s 0.3s',
          }}>
            Press ENTER or SPACE to continue
          </p>

        </div>
      )}
    </dialog>
  )
}
